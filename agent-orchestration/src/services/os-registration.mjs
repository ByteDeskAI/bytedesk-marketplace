// TM-272: the OS keeps ONE process alive — process-compose — and starts it at login. Everything
// else is process-compose's job. One plain switch per platform; no strategy classes.
//
//   linux   systemd user unit, Restart=always, WantedBy=default.target (no linger: runs while you
//           are logged in)
//   darwin  LaunchAgent, RunAtLoad + KeepAlive, through launchctl bootstrap/kickstart gui/<uid>
//   win32   Task Scheduler task from /XML: logon trigger, restart on failure, no time limit
//   detached  Linux or WSL with no usable systemd user manager: a detached process-compose that
//           every `services ensure` starts again if it is not answering
import { spawn } from "node:child_process";
import { openSync, closeSync } from "node:fs";
import { rm, writeFile, readFile, mkdir } from "node:fs/promises";
import os from "node:os";
import { dirname, join } from "node:path";
import { canonicalUserBusEnvironment, runUserManagerFile } from "../runtime/user-bus.mjs";
import { runFile } from "../util.mjs";

export const UNIT_NAME = "agent-orchestration.service";
export const LAUNCHD_LABEL = "ai.bytedesk.agent-orchestration";
export const TASK_NAME = "ByteDesk\\agent-orchestration";

const xml = (value) => String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");

/** systemd ExecStart= word: C-style quoting, plus `%` specifiers and `$` expansion disarmed. */
export function systemdQuote(value) {
  return `"${String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/%/g, "%%").replace(/\$/g, "$$$$")}"`;
}

/** One CreateProcess argument. Windows paths cannot contain `"`, so wrapping is enough. */
export function windowsQuote(value) {
  const text = String(value);
  return /[\s"]/.test(text) || text === "" ? `"${text.replace(/"/g, '\\"')}"` : text;
}

/**
 * Which mechanism this machine uses. Linux uses systemd only when the user bus answers AND the unit
 * directory is the one the user manager reads: a test or sandbox with HOME pointed elsewhere would
 * otherwise write a unit nobody loads and then start the real manager's copy.
 */
export async function registrationMode({ platform = process.platform, home = os.homedir(), env = process.env } = {}) {
  if (platform === "darwin") return "launchd";
  if (platform === "win32") return "schtasks";
  if (platform !== "linux") return "detached";
  if (home !== os.userInfo().homedir) return "detached";
  try { await canonicalUserBusEnvironment(env); return "systemd"; } catch { return "detached"; }
}

export function registrationPath({ mode, home = os.homedir(), env = process.env, servicesDir }) {
  switch (mode) {
    case "systemd": return join(env.XDG_CONFIG_HOME || join(home, ".config"), "systemd", "user", UNIT_NAME);
    case "launchd": return join(home, "Library", "LaunchAgents", `${LAUNCHD_LABEL}.plist`);
    case "schtasks": return join(servicesDir, "agent-orchestration.task.xml");
    default: return null;
  }
}

/** The registration file's text. `argv[0]` is the process-compose binary. */
export function renderRegistration({ mode, argv, logPath, path = "" }) {
  switch (mode) {
    case "systemd":
      return [
        "# Generated by `agent-orchestration services ensure`. Edits are overwritten.",
        "[Unit]",
        "Description=ByteDesk agent-orchestration services (process-compose)",
        "",
        "[Service]",
        "Type=simple",
        `ExecStart=${argv.map(systemdQuote).join(" ")}`,
        ...(path ? [`Environment=${systemdQuote(`PATH=${path}`)}`] : []),
        "Restart=always",
        "RestartSec=2",
        "TimeoutStopSec=15",
        "",
        "[Install]",
        "WantedBy=default.target",
        "",
      ].join("\n");
    case "launchd":
      return [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
        '<plist version="1.0">',
        "<dict>",
        `  <key>Label</key><string>${LAUNCHD_LABEL}</string>`,
        "  <key>ProgramArguments</key>",
        "  <array>",
        ...argv.map((arg) => `    <string>${xml(arg)}</string>`),
        "  </array>",
        "  <key>RunAtLoad</key><true/>",
        "  <key>KeepAlive</key><true/>",
        "  <key>ThrottleInterval</key><integer>5</integer>",
        ...(path ? ["  <key>EnvironmentVariables</key>", `  <dict><key>PATH</key><string>${xml(path)}</string></dict>`] : []),
        `  <key>StandardOutPath</key><string>${xml(logPath)}</string>`,
        `  <key>StandardErrorPath</key><string>${xml(logPath)}</string>`,
        "</dict>",
        "</plist>",
        "",
      ].join("\n");
    case "schtasks":
      return [
        '<?xml version="1.0" encoding="UTF-16"?>',
        '<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">',
        "  <RegistrationInfo><Description>ByteDesk agent-orchestration services (process-compose)</Description></RegistrationInfo>",
        "  <Triggers><LogonTrigger><Enabled>true</Enabled></LogonTrigger></Triggers>",
        "  <Principals><Principal id=\"Author\"><LogonType>InteractiveToken</LogonType><RunLevel>LeastPrivilege</RunLevel></Principal></Principals>",
        "  <Settings>",
        "    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>",
        "    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>",
        "    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>",
        "    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>",
        "    <RestartOnFailure><Interval>PT1M</Interval><Count>999</Count></RestartOnFailure>",
        "    <Hidden>true</Hidden>",
        "  </Settings>",
        "  <Actions Context=\"Author\">",
        "    <Exec>",
        `      <Command>${xml(argv[0])}</Command>`,
        `      <Arguments>${xml(argv.slice(1).map(windowsQuote).join(" "))}</Arguments>`,
        "    </Exec>",
        "  </Actions>",
        "</Task>",
        "",
      ].join("\n");
    default:
      return null;
  }
}

/** Runs one service-manager command. Tests replace it to record argv. */
export async function defaultRun(mode, args) {
  if (mode === "systemd") return runUserManagerFile("/usr/bin/systemctl", args, { timeoutMs: 30_000 });
  if (mode === "launchd") return runFile("/bin/launchctl", args, { timeoutMs: 30_000 });
  if (mode === "schtasks") return runFile(join(process.env.SystemRoot || "C:\\Windows", "System32", "schtasks.exe"), args, { timeoutMs: 30_000 });
  throw new Error(`No service manager command for mode ${mode}.`);
}

const quiet = (promise) => promise.then(() => true, () => false);

/**
 * Writes the registration when its text changed and applies it. Returns `{ changed, path }`.
 * `changed` is what tells the caller a running process-compose is on stale arguments.
 */
export async function register({ mode, argv, logPath, path, home, env, servicesDir, run = defaultRun, uid = process.getuid?.() }) {
  const file = registrationPath({ mode, home, env, servicesDir });
  if (!file) return { changed: false, path: null };
  const text = renderRegistration({ mode, argv, logPath, path });
  const current = await readFile(file, mode === "schtasks" ? "utf16le" : "utf8").catch(() => null);
  const normalized = current?.replace(/^\ufeff/, "") ?? null;
  if (normalized === text) return { changed: false, path: file };
  await mkdir(dirname(file), { recursive: true });
  // schtasks reads a UTF-16 document; a BOM is how it knows.
  await writeFile(file, mode === "schtasks" ? Buffer.from(`\ufeff${text}`, "utf16le") : text, { mode: 0o600 });
  switch (mode) {
    case "systemd":
      await run(mode, ["--user", "daemon-reload"]);
      await run(mode, ["--user", "enable", UNIT_NAME]);
      break;
    case "launchd":
      await quiet(run(mode, ["bootout", `gui/${uid}/${LAUNCHD_LABEL}`]));
      await run(mode, ["bootstrap", `gui/${uid}`, file]);
      break;
    case "schtasks":
      await run(mode, ["/Create", "/XML", file, "/TN", TASK_NAME, "/F"]);
      break;
  }
  return { changed: true, path: file };
}

/** Start (or, with `restart`, restart) the registered process-compose. */
export async function start({ mode, argv, logPath, run = defaultRun, uid = process.getuid?.(), restart = false, spawnDetached = defaultSpawnDetached }) {
  switch (mode) {
    case "systemd":
      return run(mode, ["--user", restart ? "restart" : "start", UNIT_NAME]);
    case "launchd":
      return run(mode, ["kickstart", ...(restart ? ["-k"] : []), `gui/${uid}/${LAUNCHD_LABEL}`]);
    case "schtasks":
      if (restart) await quiet(run(mode, ["/End", "/TN", TASK_NAME]));
      return run(mode, ["/Run", "/TN", TASK_NAME]);
    default:
      return spawnDetached(argv, logPath);
  }
}

function defaultSpawnDetached(argv, logPath) {
  const log = openSync(logPath, "a", 0o600);
  try {
    const child = spawn(argv[0], argv.slice(1), { detached: true, stdio: ["ignore", log, log], windowsHide: true });
    child.unref();
    return { pid: child.pid };
  } finally { closeSync(log); }
}

/** Remove the registration and stop what it runs. Keeps the binary and all state. */
export async function unregister({ mode, home, env, servicesDir, run = defaultRun, uid = process.getuid?.() }) {
  const file = registrationPath({ mode, home, env, servicesDir });
  switch (mode) {
    case "systemd":
      await quiet(run(mode, ["--user", "disable", "--now", UNIT_NAME]));
      if (file) await rm(file, { force: true });
      await quiet(run(mode, ["--user", "daemon-reload"]));
      break;
    case "launchd":
      await quiet(run(mode, ["bootout", `gui/${uid}/${LAUNCHD_LABEL}`]));
      if (file) await rm(file, { force: true });
      break;
    case "schtasks":
      await quiet(run(mode, ["/End", "/TN", TASK_NAME]));
      await quiet(run(mode, ["/Delete", "/TN", TASK_NAME, "/F"]));
      if (file) await rm(file, { force: true });
      break;
  }
  return { removed: file };
}

/** What the OS says about the registration, for `services status`. */
export async function registrationState({ mode, home, env, servicesDir, run = defaultRun, uid = process.getuid?.() }) {
  const file = registrationPath({ mode, home, env, servicesDir });
  const installed = file ? await readFile(file).then(() => true, () => false) : false;
  let active = null;
  if (mode === "systemd") active = await run(mode, ["--user", "is-active", UNIT_NAME]).then((r) => r.stdout.trim(), (e) => String(e.stdout ?? "inactive").trim() || "inactive");
  if (mode === "launchd") active = await quiet(run(mode, ["print", `gui/${uid}/${LAUNCHD_LABEL}`])) ? "loaded" : "not-loaded";
  if (mode === "schtasks") active = await quiet(run(mode, ["/Query", "/TN", TASK_NAME])) ? "registered" : "not-registered";
  return { mode, path: file, installed, active };
}
