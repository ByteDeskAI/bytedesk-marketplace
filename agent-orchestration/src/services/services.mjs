// NATS server, and one repository supervisor per registered repository — and restarts any that
// die. The OS keeps process-compose itself alive (os-registration.mjs). `services ensure` is the
// one idempotent entry point every caller uses: the SessionStart hook, the monitor, the lazy
// launchers, and the gateway.
